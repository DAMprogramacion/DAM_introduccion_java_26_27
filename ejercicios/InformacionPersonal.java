public class InformacionPersonal {
	
	public static void main (String[] args) {
		System.out.println("Gabriel Pestaña, avda barcelona 6, JAÉN");
		System.out.println("=======================================");
		System.out.println("Gabriel Pestaña\navda barcelona 6"); //una forma de hacerlo
		System.out.println("JAÉN"); //otra forma diferente de hacerlo
		System.out.println("=======================================");
		System.out.println("Gabriel Pestaña\n"); // el \n es un salto de línea
		System.out.println("avda barcelona");
		System.out.println(); //esto deja una línea en blanco	
		System.out.println("JAÉN");
	}
}

